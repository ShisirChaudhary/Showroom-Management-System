    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            // 1. Get Selected Car String
            String selectedStr = (String) jComboBox1.getSelectedItem();
            if (selectedStr == null) {
                JOptionPane.showMessageDialog(this, "No car selected!");
                return;
            }

            // 2. Extract ID (It's the number before " - ")
            int id = Integer.parseInt(selectedStr.split(" - ")[0]);


            // 4. Validate
            Car selectedCar = controller.getCarById(id);


            // 5. Add to Cart
            // Note: Since this is a draft cart, we are just adding the reference for now
            // In a full system, you might create a "CartItem" object with specific qty
            cartList.add(selectedCar);

            itemAdded = true;
            this.dispose(); // Close dialog

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number for quantity.");
        }
    }//GEN-LAST:event_jButton3ActionPerformed

