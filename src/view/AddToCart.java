    private void populateCarCombo() {
        if (controller == null) {
            return;
        }

        ArrayList<Car> inventory = controller.getAllCars();
        DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();

        for (Car car : inventory) {
            // Only show cars that have stock available
            if (car.getStockQuantity() > 0) {
                // Format: "ID - Model (Price)"
                model.addElement(car.getCarId() + " - " + car.getModel() + " ($" + car.getPrice() + ")");
            }
        }
        jComboBox1.setModel(model);
    }

    // Getter to let Dashboard know if we clicked "Add"
